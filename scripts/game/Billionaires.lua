assert(#DESCENDING_ROSTER == 100, "Billionaires roster must have exactly 100 entries")

local MIN_T = 1500
local MAX_T = 2.5e16
local RATIO = MAX_T / MIN_T

Billionaires.LIST = {}
local prevTarget = 0

for idx = 1, 100 do
    local rank = 101 - idx
    local src = DESCENDING_ROSTER[rank]
    local rawTarget
    if idx == 1 then
        rawTarget = MIN_T
    elseif idx == 100 then
        rawTarget = MAX_T
    else
        rawTarget = CleanRound(MIN_T * (RATIO ^ ((idx - 1) / 99)))
    end
    if rawTarget <= prevTarget then
        rawTarget = prevTarget + max(100, floor(prevTarget * 0.15))
    end
    prevTarget = rawTarget

    local bounty = max(250, floor(rawTarget * 0.12))
    local theme = (idx >= 70) and 3 or ((idx >= 35) and 2 or 1)
    local isMilestone = (rank == 50 or rank == 20 or rank == 10 or rank == 5 or rank == 3 or rank == 2 or rank == 1)

    Billionaires.LIST[idx] = {
        id = idx,
        idx = idx,
        rank = rank,
        name = src[1],
        title = src[2],
        quote = src[3],
        target = rawTarget,
        bounty = bounty,
        bonus = bounty,
        theme = theme,
        milestone = isMilestone,
        desc = string.format("No.%d %s（%s）— \"%s\"", rank, src[1], src[2], src[3]),
        avatar = {
            skin      = src[4],
            head      = src[5],
            hair      = src[6],
            hairCol   = src[7],
            glasses   = src[8],
            beard     = src[9],
            outfit    = src[10],
            outfitCol = src[11],
            prop      = src[12],
            bgTier    = (rank <= 10 and 1) or (rank <= 35 and 2) or (rank <= 70 and 3) or 4,
        },
    }
end

function Billionaires.GetByIdx(idx)
    return Billionaires.LIST[idx]
end

function Billionaires.GetByRank(rank)
    if not rank or rank < 1 or rank > 100 then return nil end
    return Billionaires.LIST[101 - rank]
end

return Billionaires
